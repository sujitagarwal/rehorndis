#!/bin/bash
# rehorndis installer.
#   /bin/bash -c "$(curl -fsSL https://raw.githubusercontent.com/sujitagarwal/rehorndis/main/install.sh)"
#
# Env overrides:
#   REHORNDIS_REPO   GitHub repo URL (default below)
#   REHORNDIS_BRANCH branch/tag to install (default: main)
#   REHORNDIS_HOME   install prefix (default: ~/.rehorndis)
#   REHORNDIS_BIN    dir for the `rehorndis` command (default: /usr/local/bin)
set -euo pipefail

REPO="${REHORNDIS_REPO:-https://github.com/sujitagarwal/rehorndis}"
BRANCH="${REHORNDIS_BRANCH:-main}"
PREFIX="${REHORNDIS_HOME:-$HOME/.rehorndis}"
BINDIR="${REHORNDIS_BIN:-/usr/local/bin}"

say()  { printf '\033[1m==>\033[0m %s\n' "$*"; }
die()  { printf '\033[31mError:\033[0m %s\n' "$*" >&2; exit 1; }

[ "$(uname -s)" = Darwin ] || die "rehorndis only runs on macOS."
[ "$(id -u)" -ne 0 ] || die "run the installer as your normal user, not root (it asks for sudo when needed)."

# --- dependencies ---
BREW="$(command -v brew || true)"
[ -z "$BREW" ] && [ -x /opt/homebrew/bin/brew ] && BREW=/opt/homebrew/bin/brew
[ -z "$BREW" ] && [ -x /usr/local/bin/brew ] && BREW=/usr/local/bin/brew
[ -n "$BREW" ] || die "Homebrew is required for libusb. Install it from https://brew.sh and re-run."
if ! "$BREW" list libusb >/dev/null 2>&1; then
  say "Installing libusb"
  "$BREW" install libusb
fi

PY="$(command -v python3 || true)"
[ -n "$PY" ] || die "python3 not found (run: xcode-select --install)."
"$PY" -c 'import sys; sys.exit(sys.version_info < (3, 9))' || die "Python 3.9+ required (found $("$PY" -V))."

# --- fetch source ---
SRC="$PREFIX/src"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd || true)"
mkdir -p "$PREFIX"
rm -rf "$SRC.new"; mkdir -p "$SRC.new"
if [ -n "$HERE" ] && [ "$HERE" != "$SRC" ] && [ -f "$HERE/main.py" ] && [ -f "$HERE/rndis.py" ]; then
  say "Installing from local checkout $HERE"
  cp "$HERE"/*.py "$HERE/requirements.txt" "$HERE/uninstall.sh" "$HERE/install.sh" "$SRC.new/"
else
  case "$REPO" in */OWNER/*) die "set REHORNDIS_REPO to the real GitHub repo URL." ;; esac
  say "Downloading $REPO ($BRANCH)"
  curl -fsSL "$REPO/archive/refs/heads/$BRANCH.tar.gz" | tar -xz -C "$SRC.new" --strip-components=1
  echo "$REPO" > "$PREFIX/repo"; echo "$BRANCH" > "$PREFIX/branch"
fi
rm -rf "$SRC"; mv "$SRC.new" "$SRC"

# --- python env ---
say "Setting up Python environment"
[ -d "$PREFIX/venv" ] || "$PY" -m venv "$PREFIX/venv"
"$PREFIX/venv/bin/pip" install -q --upgrade pip
"$PREFIX/venv/bin/pip" install -q -r "$SRC/requirements.txt"

# --- launcher ---
LAUNCHER="$PREFIX/rehorndis"
cat > "$LAUNCHER" <<EOF
#!/bin/sh
# Generated by install.sh.
PREFIX="$PREFIX"
LIBS=/opt/homebrew/lib:/usr/local/lib
PYBIN="\$PREFIX/venv/bin/python"
usage() { cat <<'USAGE'
usage: rehorndis [command]
  (none)       open the menu bar app in the background (Start/Stop from the menu)
  app          same, but in the foreground (shows errors)
  run [flags]  headless tunnel in this terminal (asks for sudo); flags: -v --dump-packets --no-default-route
  update       reinstall the latest version
  uninstall    remove ReHoRNDIS
USAGE
}
case "\${1:-}" in
  uninstall) exec /bin/bash "\$PREFIX/src/uninstall.sh" ;;
  update)    exec /bin/bash "\$PREFIX/src/install.sh" ;;
  --version) echo "rehorndis (installed at \$PREFIX)"; exit 0 ;;
  -h|--help|help) usage; exit 0 ;;
  app)       exec env DYLD_FALLBACK_LIBRARY_PATH="\$LIBS" REHORNDIS_HOME="\$PREFIX" "\$PYBIN" "\$PREFIX/src/app.py" ;;
  run)       shift
             case " \$* " in *" --help "*|*" -h "*) exec env DYLD_FALLBACK_LIBRARY_PATH="\$LIBS" "\$PYBIN" "\$PREFIX/src/main.py" "\$@" ;; esac
             exec sudo env DYLD_FALLBACK_LIBRARY_PATH="\$LIBS" "\$PYBIN" "\$PREFIX/src/main.py" "\$@" ;;
  "")        nohup env DYLD_FALLBACK_LIBRARY_PATH="\$LIBS" REHORNDIS_HOME="\$PREFIX" "\$PYBIN" "\$PREFIX/src/app.py" >>"\$PREFIX/app.log" 2>&1 &
             echo "ReHoRNDIS is in the menu bar. (rehorndis --help for more)"; exit 0 ;;
  *)         usage >&2; exit 2 ;;
esac
EOF
chmod +x "$LAUNCHER"

# --- put it on PATH ---
if [ -w "$BINDIR" ] 2>/dev/null; then
  ln -sf "$LAUNCHER" "$BINDIR/rehorndis"
else
  say "Linking $BINDIR/rehorndis (needs sudo)"
  sudo mkdir -p "$BINDIR" && sudo ln -sf "$LAUNCHER" "$BINDIR/rehorndis"
fi

# --- start at login (menu bar app); starts it now too ---
say "Enabling launch at login"
REHORNDIS_HOME="$PREFIX" "$PREFIX/venv/bin/python" "$SRC/app.py" --install-login
AGENT="$HOME/Library/LaunchAgents/com.sujitagarwal.rehorndis.plist"
launchctl bootout "gui/$(id -u)" "$AGENT" >/dev/null 2>&1 || true
launchctl bootstrap "gui/$(id -u)" "$AGENT" >/dev/null 2>&1 || true

say "Installed. Plug in the phone, enable USB tethering, then run:  rehorndis"
echo "    (opens the menu bar app; rehorndis --help for more)"
